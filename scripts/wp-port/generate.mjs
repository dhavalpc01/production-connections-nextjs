/**
 * Regenerate every converted WordPress component from the snapshots.
 *
 *   node scripts/wp-port/generate.mjs
 *
 * Add a page by saving its snapshot (curl <wp>/<path>/ > snapshots/<page>.html),
 * running capture-assets.mjs for it, and adding its jobs below.
 */

import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../..");
const converter = path.join(import.meta.dirname, "html-to-jsx.mjs");

// Service Detail pages: snapshot svc-<slug>.html, Elementor post id from its body class.
const SERVICES = [
  "website-design", "website-development", "logo-design", "brand-identity",
  "search-engine-optimization", "ai-search-optimization", "pay-per-click", "social-media-marketing",
  "email-marketing", "ai-automation-systems", "digital-strategy-marketing", "media-production",
  "targeted-tv-advertising", "billboard-advertising",
];
const pascal = (slug) => slug.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase());

const jobs = [
  // Site chrome, shared by every page (taken from the home page).
  ["home", "div.elementor-268", "src/wp/chrome/WpHeader.tsx", "WpHeader"],
  ["home", "div.elementor-4785", "src/wp/chrome/WpFooter.tsx", "WpFooter"],
  ["home", "#pum-4518", "src/wp/chrome/WpContactPopup.tsx", "WpContactPopup"],
  ["home", "div.nm-preloader", "src/wp/chrome/WpPreloader.tsx", "WpPreloader"],
  ["home", "div.wa-back-to-top", "src/wp/chrome/WpBackToTop.tsx", "WpBackToTop"],
  ["home", "div.page-wrapper > svg", "src/wp/chrome/WpSvgDefs.tsx", "WpSvgDefs"],

  // Pages.
  ["home", "div.elementor-234", "src/wp/home/HomeContent.tsx", "HomeSection", "--split"],
  ["about", "div.nm-breadcrumb-area", "src/wp/about/AboutBreadcrumb.tsx", "AboutBreadcrumb"],
  ["about", "div.elementor-220", "src/wp/about/AboutContent.tsx", "AboutSection", "--split"],
  ["contact", "div.nm-breadcrumb-area", "src/wp/contact/ContactBreadcrumb.tsx", "ContactBreadcrumb"],
  ["contact", "div.elementor-229", "src/wp/contact/ContactContent.tsx", "ContactSection", "--split"],

  // Services archive (/services/): a theme template, not Elementor.
  ["services", "div.nm-breadcrumb-area", "src/wp/services/ServicesBreadcrumb.tsx", "ServicesBreadcrumb"],
  ["services", "div.tx-blog-area", "src/wp/services/ServicesContent.tsx", "ServicesContent"],
];

const serviceEntries = [];
for (const slug of SERVICES) {
  const html = await readFile(path.join(import.meta.dirname, "snapshots", `svc-${slug}.html`), "utf8");
  const postId = html.match(/<body[^>]*\bpostid-(\d+)/)?.[1];
  if (!postId) throw new Error(`no postid in svc-${slug}.html`);
  const name = `Service${pascal(slug)}`;
  jobs.push([`svc-${slug}`, `div.elementor-${postId}`, `src/wp/services/${slug}/${name}.tsx`, name, "--split"]);
  serviceEntries.push({ slug, name });
}

// Industries: the index, five category pages (ind-<category>) and the detail
// pages (ind-<category>--<slug>), each an Elementor page whose id is in its
// body class. Professional Services' category page uses the detail template.
const pageIdOf = async (page) => {
  const html = await readFile(path.join(import.meta.dirname, "snapshots", `${page}.html`), "utf8");
  const id = html.match(/<body[^>]*\bpage-id-(\d+)/)?.[1];
  if (!id) throw new Error(`no page-id in ${page}.html`);
  return id;
};
jobs.push(["industries", `div.elementor-${await pageIdOf("industries")}`, "src/wp/industries/IndustriesContent.tsx", "IndustriesSection", "--split"]);

const { readdir } = await import("node:fs/promises");
const industryPages = (await readdir(path.join(import.meta.dirname, "snapshots")))
  .filter((file) => /^ind-.+\.html$/.test(file))
  .map((file) => file.slice(0, -5))
  .sort();
const industryEntries = [];
for (const page of industryPages) {
  const [category, slug] = page.slice(4).split("--");
  const key = slug ? `${category}/${slug}` : category;
  const name = `Industry${pascal(category)}${slug ? pascal(slug) : ""}`;
  const dir = slug ? `src/wp/industries/${category}/${slug}` : `src/wp/industries/${category}`;
  jobs.push([page, `div.elementor-${await pageIdOf(page)}`, `${dir}/${name}.tsx`, name, "--split"]);
  industryEntries.push({ key, name, file: `./${dir.slice("src/wp/industries/".length)}/${name}` });
}

for (const args of jobs) {
  execFileSync(process.execPath, [converter, ...args], { stdio: "inherit" });
}

// Registry for /industries/[category]/ and /industries/[category]/[slug]/:
// "<category>" or "<category>/<slug>" -> page component.
await writeFile(
  path.join(root, "src/wp/industries/registry.ts"),
  `// Generated by scripts/wp-port/generate.mjs.
import type { ComponentType } from "react";
${industryEntries.map(({ name, file }) => `import { ${name} } from "${file}";`).join("\n")}

export const industryPages: Record<string, ComponentType> = {
${industryEntries.map(({ key, name }) => `  ${JSON.stringify(key)}: ${name},`).join("\n")}
};
`,
);
console.log("wrote src/wp/industries/registry.ts");

// Registry for the /services/[slug] route: slug -> page component.
await writeFile(
  path.join(root, "src/wp/services/registry.ts"),
  `// Generated by scripts/wp-port/generate.mjs.
import type { ComponentType } from "react";
${serviceEntries.map(({ slug, name }) => `import { ${name} } from "./${slug}/${name}";`).join("\n")}

export const servicePages: Record<string, ComponentType> = {
${serviceEntries.map(({ slug, name }) => `  ${JSON.stringify(slug)}: ${name},`).join("\n")}
};
`,
);
console.log("wrote src/wp/services/registry.ts");
